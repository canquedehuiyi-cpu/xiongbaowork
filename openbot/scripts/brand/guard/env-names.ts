export const isKnownEnvName = (name: string): boolean =>
  [...UPSTREAM_ENV_NAMES, ...THIRD_PARTY_ENV_NAMES].some((known) =>
    known.endsWith("_") ? name.startsWith(known) : name === known,
  );
